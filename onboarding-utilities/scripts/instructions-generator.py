#!/usr/bin/env python3
"""
instructions-generator.py — Generate .github/instructions files for repositories

Reads repo-scanner JSON output and produces .github/instructions/<repo>.instructions.md
files with structured context: repo structure, dependencies, patterns, tools, conventions.

Usage:
  python3 instructions-generator.py --scan-file /path/to/repo_scan.json --output-dir /path/to/.github/instructions
  python3 instructions-generator.py --scan-dir /path/to/scans/ --output-dir /path/to/.github/instructions
    python3 instructions-generator.py --scan-dir /path/to/scans/ --output-dir /path/to/.github/instructions --repos-root /path/to/cloned/repos

Exit codes:
  0 — Success
  1 — Error
"""

import argparse
import json
import os
import sys
from pathlib import Path


def generate_instructions(scan: dict) -> str:
    """Generate a .instructions.md file from scan data."""
    repo = scan.get("repo_name", "unknown")
    pkg = scan.get("package_info", {})
    ts = scan.get("typescript", {})
    structure = scan.get("structure", {})
    patterns = scan.get("patterns", [])
    linters = scan.get("linters", {})
    formatters = scan.get("formatters", {})
    test_runners = scan.get("test_runners", {})
    ci_cd = scan.get("ci_cd", {})
    precommit = scan.get("precommit_hooks", {})
    lock_files = scan.get("lock_files", {})

    lines = []

    # Header
    lines.append(f"---")
    lines.append(f"applyTo: \"{repo}/**\"")
    lines.append(f"---")
    lines.append(f"")
    lines.append(f"# Repository Instructions — {repo}")
    lines.append(f"")
    lines.append(f"> Auto-generated by SDLC Pipeline Preflight Agent.")
    lines.append(f"> Edit this file to add custom instructions for this repository.")
    lines.append(f"")

    # Overview
    lines.append(f"## Overview")
    lines.append(f"")
    if pkg.get("name"):
        lines.append(f"- **Package:** `{pkg['name']}` v{pkg.get('version', 'N/A')}")
    if pkg.get("detected_frameworks"):
        lines.append(f"- **Frameworks:** {', '.join(pkg['detected_frameworks'])}")
    if lock_files:
        manager = list(lock_files.values())[0]
        lines.append(f"- **Package Manager:** {manager}")
    if ts and not ts.get("error"):
        lines.append(f"- **TypeScript:** strict={ts.get('strict', False)}")
    lines.append(f"- **Files:** {structure.get('total_files', 'N/A')} source files")
    lines.append(f"")

    # Repository Structure
    lines.append(f"## Repository Structure")
    lines.append(f"")
    top_dirs = structure.get("top_level_dirs", [])
    if top_dirs:
        lines.append(f"```")
        lines.append(f"{repo}/")
        for d in top_dirs[:20]:
            lines.append(f"  {d}/")
        lines.append(f"```")
        lines.append(f"")

    # File distribution by tag
    by_tag = structure.get("by_tag", {})
    if by_tag:
        lines.append(f"### File Distribution")
        lines.append(f"")
        lines.append(f"| Category | Count | Key Files |")
        lines.append(f"|----------|-------|-----------|")
        for tag, info in sorted(by_tag.items(), key=lambda x: -x[1]["count"]):
            samples = ", ".join(f"`{Path(f).name}`" for f in info.get("sample_files", [])[:3])
            lines.append(f"| {tag} | {info['count']} | {samples} |")
        lines.append(f"")

    # Dependencies & Frameworks
    if pkg and not pkg.get("error"):
        lines.append(f"## Dependencies")
        lines.append(f"")

        if pkg.get("detected_frameworks"):
            lines.append(f"### Frameworks")
            for fw in pkg["detected_frameworks"]:
                lines.append(f"- {fw}")
            lines.append(f"")

        # Key production deps (top 20)
        deps = pkg.get("dependencies", [])
        if deps:
            lines.append(f"### Key Dependencies ({len(deps)} total)")
            lines.append(f"")
            for d in sorted(deps)[:20]:
                lines.append(f"- `{d}`")
            if len(deps) > 20:
                lines.append(f"- ... and {len(deps) - 20} more")
            lines.append(f"")

    # Tools & Technologies
    lines.append(f"## Tools & Technologies")
    lines.append(f"")
    lines.append(f"| Tool Type | Tool | Config |")
    lines.append(f"|-----------|------|--------|")
    for tool, config in linters.items():
        lines.append(f"| Linter | {tool} | `{config}` |")
    for tool, config in formatters.items():
        lines.append(f"| Formatter | {tool} | `{config}` |")
    for tool, config in test_runners.items():
        lines.append(f"| Test Runner | {tool} | `{config}` |")
    for lock, manager in lock_files.items():
        lines.append(f"| Package Manager | {manager} | `{lock}` |")
    for hook_tool, config in precommit.items():
        lines.append(f"| Pre-commit | {hook_tool} | `{config}` |")
    lines.append(f"")

    # Build & Test Commands
    if pkg.get("scripts"):
        lines.append(f"## Commands")
        lines.append(f"")
        lines.append(f"| Command | Script |")
        lines.append(f"|---------|--------|")
        for name, cmd in pkg["scripts"].items():
            # Truncate very long commands
            display_cmd = cmd if len(cmd) < 80 else cmd[:77] + "..."
            lines.append(f"| `{name}` | `{display_cmd}` |")
        lines.append(f"")

    # TypeScript Config
    if ts and not ts.get("error"):
        lines.append(f"## TypeScript")
        lines.append(f"")
        lines.append(f"| Setting | Value |")
        lines.append(f"|---------|-------|")
        for k, v in ts.items():
            if v is not None:
                lines.append(f"| `{k}` | `{v}` |")
        lines.append(f"")

    # Detected Patterns
    if patterns:
        lines.append(f"## Patterns & Conventions")
        lines.append(f"")
        for p in patterns:
            lines.append(f"- **{p['pattern']}** — {p['evidence']} (confidence: {p['confidence']})")
        lines.append(f"")

    # CI/CD
    if ci_cd:
        lines.append(f"## CI/CD")
        lines.append(f"")
        for provider, config in ci_cd.items():
            if isinstance(config, list):
                lines.append(f"- **{provider}:** {', '.join(config)}")
            else:
                lines.append(f"- **{provider}:** `{config}`")
        lines.append(f"")

    # Coding Conventions (placeholder for agent to fill)
    lines.append(f"## Coding Conventions")
    lines.append(f"")
    lines.append(f"<!-- Auto-detected conventions. Edit as needed. -->")
    lines.append(f"")
    if linters.get("eslint"):
        lines.append(f"- ESLint config: `{linters['eslint']}` — refer to this file for naming and style rules")
    if formatters.get("prettier"):
        lines.append(f"- Prettier config: `{formatters['prettier']}` — auto-formatting on save")
    if ts.get("strict"):
        lines.append(f"- TypeScript strict mode enabled — all types must be explicit")
    if ts.get("paths"):
        lines.append(f"- Path aliases configured — use `@/` style imports per tsconfig paths")
    lines.append(f"")

    # Custom section placeholder
    lines.append(f"## Custom Instructions")
    lines.append(f"")
    lines.append(f"<!-- Add custom instructions for this repository below -->")
    lines.append(f"<!-- These will be read by all SDLC pipeline agents when working in this repo -->")
    lines.append(f"")

    return "\n".join(lines)


def generate_repo_copilot_instructions(scan: dict) -> str:
    """Generate per-repo .github/copilot-instructions.md content from scan data."""
    repo = scan.get("repo_name", "unknown")
    pkg = scan.get("package_info", {})
    ts = scan.get("typescript", {})
    patterns = scan.get("patterns", [])
    linters = scan.get("linters", {})
    formatters = scan.get("formatters", {})
    test_runners = scan.get("test_runners", {})
    lock_files = scan.get("lock_files", {})

    lines = []
    lines.append(f"# Copilot Instructions — {repo}")
    lines.append("")
    lines.append("> Auto-generated from repository scan results.")
    lines.append("")

    lines.append("## Project Overview")
    lines.append("")
    if pkg.get("name"):
        lines.append(f"- Package: `{pkg['name']}`")
    if pkg.get("detected_frameworks"):
        lines.append(f"- Frameworks: {', '.join(pkg['detected_frameworks'])}")
    if lock_files:
        lines.append(f"- Package manager: {', '.join(sorted(set(lock_files.values())))}")
    if ts and not ts.get("error"):
        lines.append(f"- TypeScript strict mode: `{ts.get('strict', False)}`")
    lines.append("")

    lines.append("## Coding Expectations")
    lines.append("")
    lines.append("- Follow existing file and naming conventions in this repository.")
    lines.append("- Prefer reusing existing patterns before introducing new abstractions.")
    if linters:
        lines.append(f"- Lint tooling detected: {', '.join(sorted(linters.keys()))}.")
    if formatters:
        lines.append(f"- Formatter tooling detected: {', '.join(sorted(formatters.keys()))}.")
    if test_runners:
        lines.append(f"- Test runners detected: {', '.join(sorted(test_runners.keys()))}.")
    lines.append("")

    if patterns:
        lines.append("## Detected Patterns")
        lines.append("")
        for p in patterns[:10]:
            lines.append(f"- {p.get('pattern', 'Unknown pattern')}: {p.get('evidence', 'no evidence')}.")
        lines.append("")

    lines.append("## Agent Guidance")
    lines.append("")
    lines.append("- Keep edits minimal and scoped to the requested task.")
    lines.append("- Run available tests/lint checks for touched areas when feasible.")
    lines.append("- Update related docs when behavior or developer workflow changes.")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate .github/instructions from repo scans")
    parser.add_argument("--scan-file", help="Path to a single repo scan JSON file")
    parser.add_argument("--scan-dir", help="Path to directory containing multiple scan JSON files")
    parser.add_argument("--output-dir", required=True, help="Output directory for instructions files")
    parser.add_argument("--repos-root", help="Root directory containing cloned repositories")
    args = parser.parse_args()

    if not args.scan_file and not args.scan_dir:
        print("Error: provide --scan-file or --scan-dir", file=sys.stderr)
        sys.exit(1)

    os.makedirs(args.output_dir, exist_ok=True)

    scan_files = []
    if args.scan_file:
        scan_files.append(args.scan_file)
    if args.scan_dir:
        for f in os.listdir(args.scan_dir):
            if f.endswith("_scan.json"):
                scan_files.append(os.path.join(args.scan_dir, f))

    generated = []
    generated_repo_copilot = []
    errors = []

    for scan_file in scan_files:
        try:
            with open(scan_file, "r", encoding="utf-8") as f:
                scan = json.load(f)

            repo_name = scan.get("repo_name", Path(scan_file).stem.replace("_scan", ""))
            instructions = generate_instructions(scan)

            out_path = os.path.join(args.output_dir, f"{repo_name}.instructions.md")
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(instructions)

            generated.append({"repo": repo_name, "path": out_path})
            print(f"✓ Generated: {out_path}", file=sys.stderr)

            if args.repos_root:
                repo_root = Path(args.repos_root) / repo_name
                if repo_root.exists() and repo_root.is_dir():
                    copilot_dir = repo_root / ".github"
                    copilot_dir.mkdir(parents=True, exist_ok=True)
                    copilot_path = copilot_dir / "copilot-instructions.md"
                    with open(copilot_path, "w", encoding="utf-8") as f:
                        f.write(generate_repo_copilot_instructions(scan))
                    generated_repo_copilot.append({"repo": repo_name, "path": str(copilot_path)})
                    print(f"✓ Generated: {copilot_path}", file=sys.stderr)
                else:
                    errors.append(
                        {
                            "file": scan_file,
                            "error": f"Repo path not found for copilot-instructions generation: {repo_root}",
                        }
                    )
                    print(
                        f"✗ Repo path not found for copilot-instructions generation: {repo_root}",
                        file=sys.stderr,
                    )

        except Exception as e:
            errors.append({"file": scan_file, "error": str(e)})
            print(f"✗ Error processing {scan_file}: {e}", file=sys.stderr)

    # Summary
    summary = {
        "generated": generated,
        "generated_repo_copilot_instructions": generated_repo_copilot,
        "errors": errors,
    }
    print(json.dumps(summary, indent=2))
    sys.exit(0 if not errors else 1)


if __name__ == "__main__":
    main()
